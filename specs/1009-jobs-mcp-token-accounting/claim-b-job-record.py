#!/usr/bin/env python3
"""Measure claim (b): the job_wait FILTERING delta = record metadata dropped.
Apples-to-apples: full job record (metadata JSON on disk) vs the record fields job_wait
keeps ({exit, log path}). Log-tail is CONTENT job_wait adds from the log file (reported
separately); 'note' is server-generated (unmeasurable without job_wait).
Live job_wait invocation is impossible: the mcp__jobs server is absent.
"""
import json, os, glob
jobs = glob.glob(os.path.expanduser('~/.local/state/desktop-job-queue/jobs/*.json'))
rows, field_totals = [], {}
n = 0
for p in sorted(jobs):
    try:
        r = json.load(open(p))
    except Exception:
        continue
    if r.get('state') != 'done' or 'exit' not in r or 'log' not in r:
        continue
    n += 1
    raw = os.path.getsize(p)
    keep = {"exit": r['exit'], "log": r['log']}          # record fields job_wait keeps
    kb = len(json.dumps(keep))
    try:
        tail = "\n".join(open(r['log']).read().splitlines()[:3])
    except Exception:
        tail = ""
    rows.append((raw, kb, len(tail)))
    for k, v in r.items():
        field_totals[k] = field_totals.get(k, 0) + len(json.dumps({k: v}))
assert rows, 'no completed job records'
sum_raw = sum(r[0] for r in rows)
sum_keep = sum(r[1] for r in rows)          # {exit, log} record fields only
sum_tail = sum(r[2] for r in rows)          # content job_wait adds (separate)
filter_delta = sum_raw - sum_keep           # = metadata dropped (args, pid, ...) THE FILTERING
top_drop = sorted(field_totals.items(), key=lambda x: -x[1])
print(json.dumps({
  "completed_records_measured": n,
  "sum_full_record_bytes": sum_raw,
  "sum_kept_record_fields_bytes__exit_log": sum_keep,
  "FILTERING_DELTA_bytes_metadata_dropped": filter_delta,
  "mean_filtering_delta_bytes_per_record": round(filter_delta / n, 1),
  "log_tail_content_bytes_job_wait_adds__separate": sum_tail,
  "note_field": "server-generated by job_wait; unmeasurable without invoking job_wait (server absent)",
  "per_field_total_bytes_desc": dict(top_drop),
  "fields_dropped_by_job_wait": [k for k in field_totals if k not in ("exit", "log")],
  "caveat": "Exact live job_wait result size unmeasurable (server absent). Filtering delta = record metadata that job_wait does not return, measured from real records."
}, indent=2))
